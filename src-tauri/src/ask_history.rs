//! Saved Ask conversations.
//!
//! Each chat is one small JSON file under the app data folder. Only the active
//! conversation is ever loaded into the webview; the index contains just id,
//! title, timestamp and message count. That keeps history essentially free in RAM.

use std::fs;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use tauri::{AppHandle, Manager};

const MAX_CONVERSATIONS: usize = 3;

#[derive(Serialize, Deserialize, Clone)]
#[serde(rename_all = "camelCase")]
pub struct AskSummary {
    id: String,
    title: String,
    updated_at: u64,
    messages: usize,
}

#[derive(Serialize, Deserialize, Clone)]
#[serde(rename_all = "camelCase")]
pub struct AskConversation {
    id: String,
    title: String,
    updated_at: u64,
    messages: Vec<serde_json::Value>,
}

fn folder(app: &AppHandle) -> Result<PathBuf, String> {
    let dir = app.path().app_data_dir().map_err(|error| error.to_string())?.join("ask");
    fs::create_dir_all(&dir).map_err(|error| error.to_string())?;
    Ok(dir)
}

/// IDs are generated by the webview (`crypto.randomUUID`); reject anything that
/// could escape the ask folder.
fn valid_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 80 && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

fn index_path(dir: &Path) -> PathBuf {
    dir.join("index.json")
}

fn read_index(dir: &Path) -> Vec<AskSummary> {
    fs::read(index_path(dir))
        .ok()
        .and_then(|bytes| serde_json::from_slice::<Vec<AskSummary>>(&bytes).ok())
        .unwrap_or_default()
}

fn write_index(dir: &Path, list: &[AskSummary]) -> Result<(), String> {
    let bytes = serde_json::to_vec(list).map_err(|error| error.to_string())?;
    fs::write(index_path(dir), bytes).map_err(|error| error.to_string())
}

fn summary(conversation: &AskConversation) -> AskSummary {
    AskSummary {
        id: conversation.id.clone(),
        title: conversation.title.chars().take(120).collect(),
        updated_at: conversation.updated_at,
        messages: conversation.messages.len(),
    }
}

#[tauri::command]
pub fn ask_history_list(app: AppHandle) -> Result<Vec<AskSummary>, String> {
    let dir = folder(&app)?;
    let mut list = read_index(&dir);
    list.retain(|item| valid_id(&item.id) && dir.join(format!("{}.json", item.id)).is_file());
    list.sort_by(|a, b| b.updated_at.cmp(&a.updated_at));
    Ok(list)
}

#[tauri::command]
pub fn ask_history_load(app: AppHandle, id: String) -> Result<Option<AskConversation>, String> {
    if !valid_id(&id) {
        return Err("invalid id".into());
    }
    let path = folder(&app)?.join(format!("{id}.json"));
    if !path.is_file() {
        return Ok(None);
    }
    let bytes = fs::read(path).map_err(|error| error.to_string())?;
    serde_json::from_slice(&bytes).map(Some).map_err(|error| error.to_string())
}

#[tauri::command]
pub fn ask_history_save(app: AppHandle, conversation: AskConversation) -> Result<Vec<AskSummary>, String> {
    if !valid_id(&conversation.id) {
        return Err("invalid id".into());
    }
    let dir = folder(&app)?;
    let bytes = serde_json::to_vec(&conversation).map_err(|error| error.to_string())?;
    fs::write(dir.join(format!("{}.json", conversation.id)), bytes).map_err(|error| error.to_string())?;

    let mut list = read_index(&dir);
    list.retain(|item| item.id != conversation.id);
    list.push(summary(&conversation));
    list.sort_by(|a, b| b.updated_at.cmp(&a.updated_at));
    while list.len() > MAX_CONVERSATIONS {
        if let Some(old) = list.pop() {
            let _ = fs::remove_file(dir.join(format!("{}.json", old.id)));
        }
    }
    write_index(&dir, &list)?;
    Ok(list)
}

#[tauri::command]
pub fn ask_history_delete(app: AppHandle, id: String) -> Result<Vec<AskSummary>, String> {
    if !valid_id(&id) {
        return Err("invalid id".into());
    }
    let dir = folder(&app)?;
    let _ = fs::remove_file(dir.join(format!("{id}.json")));
    let mut list = read_index(&dir);
    list.retain(|item| item.id != id);
    write_index(&dir, &list)?;
    Ok(list)
}

/// Explicit "delete all" from the chat history menu. Only files whose name is a
/// valid conversation id are removed, so nothing else in the ask folder is touched.
#[tauri::command]
pub fn ask_history_clear(app: AppHandle) -> Result<Vec<AskSummary>, String> {
    let dir = folder(&app)?;
    if let Ok(entries) = fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("json") {
                continue;
            }
            let stem = path.file_stem().and_then(|name| name.to_str()).unwrap_or_default();
            if valid_id(stem) && stem != "index" {
                let _ = fs::remove_file(path);
            }
        }
    }
    write_index(&dir, &[])?;
    Ok(Vec::new())
}
